import type { Meal, MealIngredient, Moment, Portions } from "../types";

const pot = (ingredientId: string, qty: number, unit: MealIngredient["unit"] = "g"): MealIngredient => ({
  ingredientId,
  qty,
  unit,
  role: "pot",
});
const plate = (ingredientId: string, qty: number, unit: MealIngredient["unit"] = "g"): MealIngredient => ({
  ingredientId,
  qty,
  unit,
  role: "plate_extra",
});

const meal = (
  m: Omit<Meal, "origin" | "servings" | "noCook"> & { servings?: number; noCook?: boolean },
): Meal => ({
  servings: 2,
  noCook: false,
  origin: "seed",
  ...m,
});

